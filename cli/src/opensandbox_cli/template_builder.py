def api(socket: Path, method: str, path: str, body: dict | None = None) -> str:
    import urllib.error
    import urllib.request

    url = f"http://localhost{path}"
    request = urllib.request.Request(url, method=method)
    if body is not None:
        payload = json.dumps(body).encode()
        request.add_header("Content-Type", "application/json")
        request.data = payload
    try:
        with urllib.request.urlopen(request) as response:
            return response.read().decode()
    except urllib.error.HTTPError as exc:
        raise RuntimeError(
            f"firecracker API failed: {method} {path} -> {exc.code}: {exc.read().decode()}"
        ) from exc


def _wait_for_file(path: Path, timeout_seconds: float) -> None:
    deadline = time.monotonic() + timeout_seconds
    while not path.exists():
        if time.monotonic() >= deadline:
            raise RuntimeError(f"timed out waiting for {path}")
        time.sleep(0.05)


def _wait_for_log(path: Path, marker: str, timeout_seconds: float) -> None:
    deadline = time.monotonic() + timeout_seconds
    while True:
        if path.exists() and marker in path.read_text(errors="replace"):
            return
        if time.monotonic() >= deadline:
            tail = path.read_text(errors="replace")[-2000:] if path.exists() else ""
            raise RuntimeError(
                f"timed out waiting for {marker!r} in {path}\n{tail}"
            )
        time.sleep(0.1)


def load_template(path: Path) -> dict:
    """Load and normalize a template file into its spec dict."""
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(document, dict):
        raise ValueError("template must be a YAML object")
    spec = document.get("spec") or document
    if not isinstance(spec, dict):
        raise ValueError("template spec must be a YAML object")
    spec.setdefault("machine", _default_machine())
    spec.setdefault("output", _default_output())
    return spec
