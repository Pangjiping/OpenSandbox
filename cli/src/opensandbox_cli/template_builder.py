"""SandboxTemplate build engine.

Implements the SandboxTemplate pipeline: convert an OCI archive
into a Firecracker rootfs with the OpenSandbox runtime injected, optionally
boot it for validation, create a full snapshot, and package the artifacts as
OverlayBD LSMT layers. The engine shells out to focused external tools
(oci2rootfs, firecracker, e2fsprogs, overlaybd toolchain) and emits a
content-addressed manifest plus SHA256SUMS.
"""

from __future__ import annotations

import hashlib
import json
