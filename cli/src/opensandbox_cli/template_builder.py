FORMATS = ("ext4", "snapshot", "overlaybd")

_QUANTITY_RE = re.compile(r"^(\d+)(Gi|Mi|Ki|G|M|K)?$", re.IGNORECASE)


def parse_quantity(value: str) -> int:
    """Parse a Kubernetes-style resource quantity into an integer (bytes or
    millis). ``"4"`` → 4, ``"4000m"`` → 4, ``"8Gi"`` → 8589934592."""
    if value is None:
        raise ValueError("quantity is required")
    value = str(value).strip()
    if value.endswith("m") and not value.endswith(("Mi", "Ki", "Gi")):
        number = value[:-1]
        if number.isdigit():
            return max(1, int(number) // 1000 or 1)
    match = _QUANTITY_RE.match(value)
    if not match:
        raise ValueError(f"invalid resource quantity: {value!r}")
    number, suffix = match.groups()
    multiplier = {
        None: 1,
        "K": 1000,
        "KI": 1024,
        "M": 1000**2,
        "MI": 1024**2,
        "G": 1000**3,
        "GI": 1024**3,
    }
    return int(number) * multiplier[suffix.upper() if suffix else None]


def _default_machine() -> dict:
    return {"vcpu": "1", "memory": "2Gi"}


def _default_output() -> dict:
    return {"rootfsSize": "30Gi", "format": "ext4"}


def template_defaults() -> dict:
    """A template skeleton with documented defaults, as generated by
    ``osb template init``."""
    return {
        "apiVersion": "sandbox.opensandbox.io/v1alpha1",
        "kind": "SandboxTemplate",
        "metadata": {"name": "example-sandbox"},
        "spec": {
            "image": "registry.example.com/sandbox:v1.0.0",
            "entrypoint": ["tail", "-f", "/dev/null"],
            "execd": "registry.example.com/execd:v1.0.0",
            "kernel": "vmlinux-6.1.177",
            "machine": _default_machine(),
            "init": "/usr/local/sbin/guest-init",
            "envs": [{"name": "EXAMPLE", "value": "1"}],
            "readiness": {"probe": "tcp://127.0.0.1:44772", "warmupSeconds": 60, "healthCheck": ""},
            "output": _default_output(),
        },
    }


def validate_template(spec: dict) -> list[str]:
    """Validate a template spec and return a list of human-readable errors.
    An empty list means the template is valid."""
    errors: list[str] = []

    def require(field: str) -> str | None:
        value = spec.get(field)
        if not value:
            errors.append(f"spec.{field} is required")
        return value

    image = require("image")
    kernel = require("kernel")
    del image, kernel

    entrypoint = spec.get("entrypoint")
    if entrypoint is not None and not isinstance(entrypoint, list):
        errors.append("spec.entrypoint must be an argv list")

    machine = spec.get("machine", {})
    for quantity_field in ("vcpu", "memory"):
        raw = machine.get(quantity_field)
        if raw is None:
            continue
        try:
            parse_quantity(raw)
        except ValueError as exc:
            errors.append(f"spec.machine.{quantity_field}: {exc}")

    output = spec.get("output", {})
    fmt = output.get("format", "ext4")
    if fmt not in FORMATS:
        errors.append(f"spec.output.format must be one of {', '.join(FORMATS)}")
    rootfs_size = output.get("rootfsSize")
    if rootfs_size is not None:
        try:
            parse_quantity(rootfs_size)
        except ValueError as exc:
            errors.append(f"spec.output.rootfsSize: {exc}")

    readiness = spec.get("readiness", {})
    warmup = readiness.get("warmupSeconds")
    if warmup is not None and (not isinstance(warmup, int) or warmup < 0):
        errors.append("spec.readiness.warmupSeconds must be a non-negative integer")
    probe = readiness.get("probe")
    if probe is not None and not probe.startswith(("tcp://", "cmd://")):
        errors.append('spec.readiness.probe must start with "tcp://" or "cmd://"')

    envs = spec.get("envs")
    if envs is not None:
        if not isinstance(envs, list):
            errors.append("spec.envs must be a list")
        else:
            for index, entry in enumerate(envs):
                if not isinstance(entry, dict) or not entry.get("name"):
                    errors.append(f"spec.envs[{index}] must be an object with a name")

    prime = output.get("prime")
    if prime is not None:
        selector = prime.get("nodeSelector")
        if not isinstance(selector, dict) or not selector:
            errors.append("spec.output.prime.nodeSelector must be a non-empty map")

    return errors


