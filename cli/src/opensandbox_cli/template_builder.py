@dataclass
class BuildResult:
    """Files produced by a build, keyed by their artifact name."""

    directory: Path
    files: dict[str, Path] = field(default_factory=dict)
    timing: dict[str, float] = field(default_factory=dict)
    restored: bool = False
    restore_iterations: int = 0
    restore_timing: dict[str, float] = field(default_factory=dict)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def build_manifest(spec: dict, result: BuildResult, kernel_digest: str, source_digest: str) -> dict:
    """Assemble the content-addressed manifest schema."""
    files: dict[str, dict] = {}
    for name, path in result.files.items():
        entry: dict[str, object] = {"sha256": sha256_file(path)}
        size = path.stat().st_size
        if size:
            entry["sizeBytes"] = size
        files[name] = entry

    validation: dict[str, object] = {
        "booted": bool(result.files.get("rootfs.ext4")),
        "timing": result.timing,
    }
    if result.restored:
        validation["restored"] = True
        validation["iterations"] = result.restore_iterations
        validation["restoreTiming"] = result.restore_timing

    machine = spec.get("machine", _default_machine())
    output = spec.get("output", _default_output())
    return {
        "schemaVersion": 1,
        "sourceImage": spec.get("image", ""),
        "sourceImageDigest": source_digest or "",
        "execd": spec.get("execd", ""),
        "kernel": {"name": spec.get("kernel", ""), "digest": kernel_digest or ""},
        "machine": {"vcpu": machine.get("vcpu", "1"), "memory": machine.get("memory", "2Gi")},
        "compatibility": {
            "firecrackerVersion": _tool_version("firecracker"),
            "architecture": platform.machine(),
            "cpuModel": _cpu_model(),
            "hostKernel": platform.release(),
        },
        "entrypoint": spec.get("entrypoint") or ["tail", "-f", "/dev/null"],
        "init": spec.get("init", ""),
        "envs": spec.get("envs") or [],
        "rootfsSize": output.get("rootfsSize", "30Gi"),
        "format": output.get("format", "ext4"),
        "files": files,
        "validation": validation,
    }


def write_checksums(directory: Path, files: dict[str, Path]) -> None:
    """Write SHA256SUMS over the produced artifact files and verify it with
    the Python hasher (no external sha256sum dependency)."""
    lines = []
    for name in sorted(files):
        lines.append(f"{sha256_file(files[name])}  {name}")
    checksums = directory / "SHA256SUMS"
    checksums.write_text("\n".join(lines) + "\n", encoding="utf-8")
    for line in lines:
        digest, name = line.split("  ", 1)
        actual = sha256_file(directory / name)
        if actual != digest:
            raise RuntimeError(f"checksum mismatch for {name}: {actual} != {digest}")


def _tool_version(binary: str) -> str:
    for flag in ("--version", "-v"):
        try:
            output = subprocess.run(
                [binary, flag], capture_output=True, text=True, timeout=10
            ).stdout
            return output.strip().splitlines()[0] if output.strip() else ""
        except (OSError, subprocess.TimeoutExpired):
            continue
    return ""


def _cpu_model() -> str:
    if sys.platform != "linux":
        return ""
    try:
        with open("/proc/cpuinfo", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return ""


