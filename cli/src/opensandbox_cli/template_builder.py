def _run(command: list[str], cwd: Path | None = None) -> None:
    """Run a stage command with combined output surfaced on failure."""
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(
            f"command failed ({result.returncode}): {' '.join(command)}\n{result.stdout}\n{result.stderr}"
        )


def _require_tool(name: str, env_var: str, cli_flag: str | None) -> str:
    """Resolve an external tool: explicit flag, environment variable, then PATH."""
    if cli_flag:
        return cli_flag
    override = os.environ.get(env_var)
    if override:
        return override
    found = shutil.which(name)
    if not found:
        raise RuntimeError(
            f"required tool '{name}' not found on PATH; set {env_var} or pass a path flag"
        )
    return found


