def stage_convert(
    spec: dict,
    workdir: Path,
    oci_archive: Path,
    execd_dir: Path | None,
    oci2rootfs: str,
    guest_init: str,
) -> tuple[Path, str]:
    """Materialize the OCI layers into a sparse ext4 rootfs and inject the
    OpenSandbox runtime, the optional guest init, and the sandbox env."""
    rootfs = workdir / "rootfs.ext4"
    rootfs_size = parse_quantity(spec.get("output", {}).get("rootfsSize", "30Gi"))
    size_gib = max(1, rootfs_size // (1024**3))

    _run(
        [
            oci2rootfs,
            str(oci_archive),
            "--output",
            str(rootfs),
            "--size",
            f"{size_gib}G",
            "--platform",
            "linux/amd64",
        ]
    )
    _run(["e2fsck", "-fy", str(rootfs)])

    mount_point = workdir / ".rootfs-mount"
    mount_point.mkdir(exist_ok=True)
    try:
        _run(["mount", "-o", "loop", str(rootfs), str(mount_point)])
        _inject_runtime(spec, mount_point, execd_dir, guest_init)
        subprocess.run(["sync"], check=True)
    finally:
        subprocess.run(["umount", str(mount_point)], capture_output=True)
        shutil.rmtree(mount_point, ignore_errors=True)
    _run(["e2fsck", "-fn", str(rootfs)])
    return rootfs, sha256_file(rootfs)


def _inject_runtime(
    spec: dict, mount_point: Path, execd_dir: Path | None, guest_init: str
) -> None:
    """Inject execd bootstrap files, the optional guest init, and the
    sandbox environment into the mounted rootfs."""
    opt = mount_point / "opt" / "opensandbox"
    opt.mkdir(parents=True, exist_ok=True)
    if execd_dir is not None:
        for name in ("execd", "bootstrap.sh", "prepare.sh", "bwrap"):
            source = execd_dir / name
            if source.is_file():
                shutil.copy2(source, opt / name)
                os.chmod(opt / name, 0o755)

    if spec.get("init"):
        sbin = mount_point / "usr" / "local" / "sbin"
        sbin.mkdir(parents=True, exist_ok=True)
        shutil.copy2(guest_init, sbin / "sandbox-init")
        os.chmod(sbin / "sandbox-init", 0o755)

    env_file = mount_point / "etc" / "sandbox-init.env"
    lines = []
    for entry in spec.get("envs") or []:
        lines.append(f"export {entry['name']}={entry.get('value', '')!r}")
    entrypoint = spec.get("entrypoint") or ["tail", "-f", "/dev/null"]
    lines.append(f"export ENTRYPOINT={' '.join(entrypoint)!r}")
    env_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.chmod(env_file, 0o600)

    hosts = mount_point / "etc" / "hosts"
    if not hosts.exists():
        hosts.write_text("127.0.0.1 localhost\n::1 localhost ip6-localhost ip6-loopback\n")


def stage_validate_boot(
    spec: dict,
    workdir: Path,
    kernel: Path,
    firecracker: str,
    api_socket: Path,
    console_log: Path,
    timeout_seconds: float,
) -> None:
    """Boot the rootfs, wait for guest readiness, and stop. This is the
    terminal validation gate for the ext4 format."""
    _run([firecracker, "--api-sock", str(api_socket)], cwd=workdir)
    _wait_for_file(api_socket, 15)

    rootfs = workdir / "rootfs.ext4"
    machine = spec.get("machine", _default_machine())
    vcpu = max(1, parse_quantity(machine.get("vcpu", "1")) // 1000 or 1)
    memory_mib = parse_quantity(machine.get("memory", "2Gi")) // (1024**2)

    boot_args = (
        "console=ttyS0 reboot=k panic=1 pci=off nomodules "
        "root=/dev/vda rw"
    )
    if spec.get("init"):
        boot_args += " init=/usr/local/sbin/sandbox-init"

    api(api_socket, "PUT", "/machine-config",
        {"vcpu_count": vcpu, "mem_size_mib": memory_mib, "smt": False})
    api(api_socket, "PUT", "/boot-source",
        {"kernel_image_path": str(kernel), "boot_args": boot_args})
    api(api_socket, "PUT", f"/drives/{'rootfs'}",
        {"drive_id": "rootfs", "path_on_host": str(rootfs),
         "is_root_device": True, "is_read_only": False})
    api(api_socket, "PUT", "/actions", {"action_type": "InstanceStart"})

    _wait_for_log(console_log, "SANDBOX_READY", timeout_seconds)
    api(api_socket, "PATCH", "/vm", {"state": "Paused"})
    api(api_socket, "PUT", "/actions", {"action_type": "SendCtrlAltDel"})


def stage_snapshot(
    spec: dict, workdir: Path, api_socket: Path, timeout_seconds: float
) -> tuple[Path, Path]:
    """Create a full snapshot from the paused VM and restore once for
    validation."""
    vmstate = workdir / "vmstate.snap"
    memory = workdir / "memory.snap"
    api(api_socket, "PUT", "/snapshot/create",
        {"snapshot_type": "Full", "snapshot_path": str(vmstate),
         "mem_file_path": str(memory)})
    api(api_socket, "PUT", "/actions", {"action_type": "FlushMetrics"})

    restore_socket = workdir / "restore.sock"
    restore_log = workdir / "restore.console.log"
    _run(["pkill", "-f", "firecracker.*sandbox-init"], cwd=workdir)
    time.sleep(0.5)
    _run(["firecracker", "--api-sock", str(restore_socket)], cwd=workdir)
    _wait_for_file(restore_socket, 15)
    api(restore_socket, "PUT", "/snapshot/load",
        {"snapshot_path": str(vmstate),
         "mem_backend": {"backend_type": "File", "backend_path": str(memory)},
         "resume_vm": True})
    _wait_for_log(restore_log, "SANDBOX_READY", timeout_seconds)
    return vmstate, memory


def stage_package(
    workdir: Path, overlaybd_import: str, rootfs: Path, memory: Path | None
) -> None:
    """Convert rootfs (and memory, for snapshot formats) into OverlayBD LSMT
    commit layers."""
    for name, source in (("rootfs", rootfs), ("memory", memory)):
        if source is None:
            continue
        destination = workdir / "overlaybd" / name
        destination.mkdir(parents=True, exist_ok=True)
        data = destination / "layer.data.tmp"
        index = destination / "layer.index.tmp"
        commit = destination / "layer.commit.tmp"
        _run([overlaybd_import, str(source), str(data), str(index), str(commit)])
        data.unlink(missing_ok=True)
        index.unlink(missing_ok=True)
        commit.rename(destination / "layer.lsmt")


